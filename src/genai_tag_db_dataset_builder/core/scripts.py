_KANA_RE = re.compile("[\u3040-\u30ff]")
_HANGUL_RE = re.compile("[\uac00-\ud7af]")
_CJK_RE = re.compile("[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]")


def has_kana(text: str) -> bool:
    return _KANA_RE.search(text) is not None


def guess_language_by_script(text: str) -> str | None:
    """文字種から翻訳の言語コードを推定する (ja / ko / zh / 判定不能は None).

    - ハングルを含む → ko
    - 仮名を含む → ja
    - 漢字のみ → zh (漢字のみの訳語は日本語・繁体字中国語を区別できないため zh 扱い)
    - それ以外 (ラテン文字・キリル文字・タイ文字など) → None (取り込まない)
    """
    if _HANGUL_RE.search(text):
        return "ko"
    if has_kana(text):
        return "ja"
    if _CJK_RE.search(text):
        return "zh"
    return None
